# -*- coding: utf-8 -*-
"""Конвертация раскладки клавиатуры (ЙЦУКЕН «вверх ногами»).

Если пользователь набрал русский текст на английской раскладке — отправляется
латиница, которую FTS/vector не матчат («gj vjitcnm» вместо «на проверить»).
Здесь мы определяем такой случай и конвертируем строку в кириллицу.

Безопасность: конвертируем ТОЛЬКО чисто латинский текст, где большая часть
букв имеют кириллический аналог. Тексты с кириллицей («как настроить API»)
и исконный английский («parts resource rest api») не трогаем.
"""
import re

# Наборы символов по виртуальным скан-кодам: русская раскладка -> английская.
# key = русский символ, value = английский символ, который нажимается на клавише.
_RU_TO_EN = {
    'й': 'q', 'ц': 'w', 'у': 'e', 'к': 'r', 'е': 't', 'н': 'y', 'г': 'u',
    'ш': 'i', 'щ': 'o', 'з': 'p', 'х': '[', 'ъ': ']', 'ф': 'a', 'ы': 's',
    'в': 'd', 'а': 'f', 'п': 'g', 'р': 'h', 'о': 'j', 'л': 'k', 'д': 'l',
    'ж': ';', 'э': "'", 'я': 'z', 'ч': 'x', 'с': 'c', 'м': 'v', 'и': 'b',
    'т': 'n', 'ь': 'm', 'б': ',', 'ю': '.', 'ё': '`',
}

# Цифры/спецсимволы совпадают в обеих раскладках — конвертировать не нужно.
_NON_LETTER_RU = set('. , ; : - " \' [ ] `'.split())

_EN_TO_RU = {v: k for k, v in _RU_TO_EN.items()}

_RE_CYRILLIC = re.compile('[а-яё]', re.I)
_RE_LATIN = re.compile('[a-zA-Z]')


def to_cyrillic(text: str) -> str:
    """Переводит строку из английской раскладки в кириллическую."""
    return ''.join(_EN_TO_RU.get(c, c) for c in text)


def detect_and_fix_layout(text: str) -> str:
    """Возвращает текст с исправленной раскладкой, если она неверная.

    Критерий: текст не содержит кириллицы, но содержит латиницу, и более 50%
    латинских букв имеют кириллический аналог (т.е. это «русский на lat»).
    Иначе возвращает текст без изменений.
    """
    if not text:
        return text
    if _RE_CYRILLIC.search(text):
        return text  # есть кириллица — раскладка верная, латиница это термины

    latin = _RE_LATIN.findall(text)
    if not latin:
        return text  # нет латиницы — раскладка верная (кириллица/цифры)

    convertible = sum(1 for c in latin if c in _EN_TO_RU)
    if convertible / len(latin) > 0.5:
        return to_cyrillic(text)
    return text


if __name__ == "__main__":
    import sys
    for line in sys.argv[1:]:
        print(detect_and_fix_layout(line))
